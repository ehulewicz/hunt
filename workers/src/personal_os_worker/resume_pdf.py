from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
from pathlib import Path
from typing import Any

# Layout is Jake Gutierrez's "Jake's Resume" template as adapted for
# bin/Sam_Kim_resume_dec2027.pdf: 11pt newtx Times, small-caps section rules,
# and role-first two-row entries.
#
# Two deliberate departures from the supplied source:
#
#  1. \PassOptionsToPackage for color. newtx pulls color in itself on current
#     TeX Live, so a later \usepackage[usenames,dvipsnames]{color} raises an
#     option clash. Passing the options ahead of any loader keeps the intent.
#  2. \resumeEducation takes a prebuilt row block instead of a fixed pair of
#     degree rows. The supplied macro hard-codes exactly two degrees; building
#     the rows in Python emits identical output for two and still handles one.
PREAMBLE = r"""%-------------------------
% Resume in LaTeX
% Based off of: Jake Gutierrez's "Jake's Resume" template
% License: MIT
% Generated by the hunt CLI from resume JSON. Do not edit by hand.
%------------------------

\documentclass[letterpaper,11pt]{article}

% newtx loads color itself, so these options must reach the package before any
% other loader gets to it. Without this the document fails with an option clash.
\PassOptionsToPackage{usenames,dvipsnames}{color}

\usepackage[T1]{fontenc}
% Times text + math (real bold small caps; matches original metrics)
\usepackage{newtxtext,newtxmath}
\usepackage{latexsym}
\usepackage[empty]{fullpage}
\usepackage{titlesec}
\usepackage{marvosym}
\usepackage[usenames,dvipsnames]{color}
\usepackage{verbatim}
\usepackage{enumitem}
\usepackage[hidelinks]{hyperref}
\usepackage{fancyhdr}
\usepackage[english]{babel}
\usepackage{tabularx}
\input{glyphtounicode}

\pagestyle{fancy}
\fancyhf{} % clear all header and footer fields
\fancyfoot{}
\renewcommand{\headrulewidth}{0pt}
\renewcommand{\footrulewidth}{0pt}

% Adjust margins
\addtolength{\oddsidemargin}{-0.5in}
\addtolength{\evensidemargin}{-0.5in}
\addtolength{\textwidth}{1in}
\addtolength{\topmargin}{-.5in}
\addtolength{\textheight}{1.0in}

\urlstyle{same}

\raggedbottom
\raggedright
\setlength{\tabcolsep}{0in}

% Sections formatting
\titleformat{\section}{
  \vspace{-4pt}\scshape\raggedright\large
}{}{0em}{}[\color{black}\titlerule \vspace{-5pt}]

% Ensure that generate pdf is machine readable/ATS parsable
\pdfgentounicode=1

%-------------------------
% Custom commands
\newcommand{\resumeItem}[1]{
  \item\small{#1}\vspace{-2pt}
}

\newcommand{\resumeSubheading}[4]{
  \vspace{-2pt}\item
    \begin{tabular*}{0.97\textwidth}[t]{l@{\extracolsep{\fill}}r}
      \textbf{#1} & #2 \\
      \textit{\small#3} & \textit{\small #4} \\
    \end{tabular*}\vspace{-6pt}
}

% School with any number of degree lines plus a coursework line, all on one
% baseline grid. #3 carries the already-formatted rows.
\newcommand{\resumeEducation}[3]{
  \vspace{-2pt}\item
    \begin{tabular*}{0.97\textwidth}[t]{l@{\extracolsep{\fill}}r}
      \textbf{#1} & #2 \\
      #3
    \end{tabular*}\vspace{-7pt}
}

\newcommand{\resumeSubSubheading}[2]{
    \item
    \begin{tabular*}{0.97\textwidth}{l@{\extracolsep{\fill}}r}
      \textit{\small#1} & \textit{\small #2} \\
    \end{tabular*}\vspace{-7pt}
}

\newcommand{\resumeProjectHeading}[2]{
    \item
    \begin{tabular*}{0.97\textwidth}{l@{\extracolsep{\fill}}r}
      \small#1 & #2 \\
    \end{tabular*}\vspace{-7pt}
}

\newcommand{\resumeSubItem}[1]{\resumeItem{#1}\vspace{-4pt}}

\renewcommand\labelitemii{$\vcenter{\hbox{\tiny$\bullet$}}$}

\newcommand{\resumeSubHeadingListStart}{\begin{itemize}[leftmargin=0.15in, label={}]}
\newcommand{\resumeSubHeadingListEnd}{\end{itemize}}
\newcommand{\resumeItemListStart}{\begin{itemize}}
\newcommand{\resumeItemListEnd}{\end{itemize}\vspace{-5pt}}
"""

REPRODUCIBLE_EPOCH = "946684800"  # 2000-01-01T00:00:00Z

# A resume build is valid only when the reference-style layout stays on one page.
MAXIMUM_PAGES: int | None = 1

# Rendered in this order. A section with no entries emits nothing at all, so one
# generator serves a resume with Research and no Leadership and the reverse.
ENTRY_SECTIONS: tuple[tuple[str, str], ...] = (
    ("experience", "Experience"),
    ("research", "Research"),
    ("projects", "Projects"),
    ("leadership", "Leadership"),
)


def latex_environment() -> dict[str, str]:
    environment = os.environ.copy()
    environment["SOURCE_DATE_EPOCH"] = REPRODUCIBLE_EPOCH
    environment["FORCE_SOURCE_DATE"] = "1"
    return environment


def compile_resume(resume: dict[str, Any], output_directory: Path) -> Path:
    return compile_pdf(build_latex(resume), output_directory, "resume", pages=MAXIMUM_PAGES)


def compile_pdf(latex: str, output_directory: Path, stem: str, *, pages: int | None) -> Path:
    """Run latexmk on `latex` as `<stem>.tex` and verify the page budget."""
    output_directory.mkdir(parents=True, exist_ok=True)
    source = output_directory / f"{stem}.tex"
    source.write_text(latex, encoding="utf-8")
    process = subprocess.run(
        [
            "latexmk",
            "-pdf",
            "-interaction=nonstopmode",
            "-halt-on-error",
            f"-outdir={output_directory}",
            str(source),
        ],
        check=False,
        capture_output=True,
        env=latex_environment(),
        text=True,
        timeout=120,
    )
    pdf = output_directory / f"{stem}.pdf"
    if process.returncode != 0 or not pdf.exists():
        raise RuntimeError((process.stdout + "\n" + process.stderr)[-2000:])
    page_check = subprocess.run(
        ["pdfinfo", str(pdf)], check=False, capture_output=True, text=True, timeout=15
    )
    found = re.search(r"^Pages:\s+(\d+)$", page_check.stdout, re.MULTILINE)
    if page_check.returncode != 0 or found is None:
        raise RuntimeError(f"Could not verify the generated {stem} page count")
    if pages is not None and int(found.group(1)) > pages:
        raise RuntimeError(f"{stem} must stay within {pages} page(s); generated {found.group(1)}")
    return pdf


def build_latex(resume: dict[str, Any]) -> str:
    serialized = json.dumps(resume, sort_keys=True, separators=(",", ":"))
    trailer_id = hashlib.sha256(serialized.encode()).hexdigest()[:32].upper()
    parts = [
        PREAMBLE,
        rf"\pdftrailerid{{<{trailer_id}><{trailer_id}>}}",
        r"\begin{document}",
    ]
    parts.extend(build_header(resume.get("contact", {})))
    parts.extend(build_education(resume.get("education", {})))
    for key, label in ENTRY_SECTIONS:
        parts.extend(build_entries(label, resume.get(key, [])))
    parts.extend(build_skills(resume.get("skills", [])))
    parts.append(r"\end{document}")
    return "\n".join(parts) + "\n"


def build_header(contact: dict[str, Any]) -> list[str]:
    details: list[str] = []
    citizenship = str(contact.get("citizenship", "")).strip()
    if citizenship:
        details.append(escape(citizenship))
    phone = str(contact.get("phone", "")).strip()
    if phone:
        details.append(escape(phone))
    email = str(contact.get("email", "")).strip()
    if email:
        details.append(rf"\href{{mailto:{email}}}{{\underline{{{escape(email)}}}}}")
    for key in ("linkedin", "github"):
        link = str(contact.get(key, "")).strip()
        if link:
            details.append(rf"\href{{{link}}}{{\underline{{{escape(display_url(link))}}}}}")
    return [
        r"\begin{center}",
        rf"    \textbf{{\Huge \scshape {escape(str(contact.get('name', '')))}}} \\ \vspace{{1pt}}",
        r"    \small " + " $|$\n    ".join(details),
        r"\end{center}",
    ]


def build_education(education: dict[str, Any]) -> list[str]:
    if not education:
        return []
    rows = [
        rf"      \textit{{\small {escape(degree)}}} & \textit{{\small {escape(date)}}} \\"
        for degree, date in education_degrees(education)
    ]
    courses = str(education.get("courses", "")).strip()
    if courses:
        rows.append(rf"      \small \textbf{{Core Coursework}}: {escape(courses)} & \\")
    return [
        r"\section{Education}",
        r"  \resumeSubHeadingListStart",
        r"    \resumeEducation",
        (
            rf"      {{{escape(str(education.get('school', '')))}}}"
            rf"{{{escape(str(education.get('location', '')))}}}"
        ),
        "      {%",
        *rows,
        "      }",
        r"  \resumeSubHeadingListEnd",
    ]


def education_degrees(education: dict[str, Any]) -> list[tuple[str, str]]:
    """Return the degree rows as (text, date) pairs.

    ``degrees`` is the current shape and carries one entry per awarded degree.
    The older flat ``degree``/``threads``/``gpa``/``graduation`` fields still
    render, as a single row, so a resume written against the previous schema
    keeps building untouched.
    """
    declared = education.get("degrees")
    if isinstance(declared, list) and declared:
        return [
            (str(row.get("degree", "")).strip(), str(row.get("date", "")).strip())
            for row in declared
            if isinstance(row, dict)
        ]
    degree = str(education.get("degree", "")).strip()
    if not degree:
        return []
    threads = str(education.get("threads", "")).strip()
    if threads:
        degree = f"{degree} | Threads: {threads}"
    gpa = str(education.get("gpa", "")).strip()
    scale = str(education.get("gpaScale", "")).strip()
    if gpa and scale:
        gpa = f"{gpa}/{scale}"
    if gpa:
        degree = f"{degree} | GPA: {gpa}"
    return [(degree, str(education.get("graduation", "")).strip())]


def build_entries(title: str, entries: list[dict[str, Any]]) -> list[str]:
    """Render one section, or nothing when the section is empty.

    An entry with an organization gets the two-row role-first heading. One
    without gets the single-row project heading, which is how the reference sets
    projects and anything else that has no separate employer.
    """
    if not entries:
        return []
    lines = [rf"\section{{{title}}}", r"  \resumeSubHeadingListStart"]
    for entry in entries:
        role = escape(str(entry.get("title", "")))
        org = escape(str(entry.get("org", "") or ""))
        location = escape(str(entry.get("location", "") or ""))
        date = escape(str(entry.get("date", "")))
        qualifier = escape(str(entry.get("qualifier", "") or "").strip())
        if qualifier:
            date = rf"\textit{{{qualifier}}} $|$ {date}"
        if org:
            lines.append(rf"    \resumeSubheading{{{role}}}{{{date}}}{{{org}}}{{{location}}}")
        else:
            lines.append(rf"    \resumeProjectHeading{{\textbf{{{role}}}}}{{{date}}}")
        lines.append(r"      \resumeItemListStart")
        lines.extend(
            rf"        \resumeItem{{{escape(str(bullet))}}}" for bullet in entry.get("bullets", [])
        )
        lines.append(r"      \resumeItemListEnd")
    lines.append(r"  \resumeSubHeadingListEnd")
    return lines


def build_skills(skills: list[dict[str, Any]]) -> list[str]:
    """Render every skill category as one item of backslash-separated lines.

    The reference sets the whole block as a single list item rather than one
    item per category, which is what keeps the categories tight against each
    other instead of inheriting the list's inter-item spacing.
    """
    if not skills:
        return []
    rows = [
        rf"     \textbf{{{escape(str(skill.get('category', '')))}}}"
        rf"{{: {escape(str(skill.get('items', '')))}}}"
        for skill in skills
    ]
    return [
        r"\section{Technical Skills}",
        r" \begin{itemize}[leftmargin=0.15in, label={}]",
        r"    \small{\item{",
        " \\\\\n".join(rows),
        r"    }}",
        r" \end{itemize}",
    ]


def display_url(url: str) -> str:
    return re.sub(r"^https?://(www\.)?", "", url).rstrip("/")


def escape(value: str) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
        "|": r"\textbar{}",
        "–": "--",  # noqa: RUF001 - the authored en dash intentionally maps to TeX.
        "—": "---",
    }
    return "".join(replacements.get(character, character) for character in value)
