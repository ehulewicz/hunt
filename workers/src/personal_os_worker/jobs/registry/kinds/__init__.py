"""Control kinds: what a widget is, independent of the ATS and the question.

Two widgets are the same control if and only if the same strategy operates
them. Seven kinds cover every form control the worker has met, generated by
payload (value or file), where the options live (free, in the DOM at rest, or
only after interaction), and cardinality (one, many, boolean).
"""

from __future__ import annotations

import json
import re
from typing import Any

from personal_os_worker.core import page_scripts

CONTROL_KINDS = (
    "text_entry",
    "native_select",
    "choice_group",
    "multi_choice_group",
    "toggle",
    "dynamic_choice",
    "file",
)
# `yesno` is the detector's name for a group of aria-pressed buttons; it is a
# synthetic type, not an HTML one.
BUTTON_GROUP = "yesno"
# A gate's ways into the application (`jobs/gateway.py`): buttons, no input of
# their own, operated by clicking the one the fact names — a choice group.
GATEWAY = "gateway"


def _lower(field: dict[str, Any], key: str) -> str:
    return str(field.get(key) or "").strip().casefold()


def classify(field: dict[str, Any]) -> str:
    # A widget a custom kind captured is that kind (`registry/kinds/custom.py`).
    if field.get("custom"):
        return str(field["custom"])
    tag, field_type, role = _lower(field, "tag"), _lower(field, "type"), _lower(field, "role")
    if field_type == "file":
        return "file"
    if tag == "select":
        return "multi_choice_group" if field.get("multiple") is True else "native_select"
    if role == "combobox":
        return "dynamic_choice"
    if field_type in {"radio", BUTTON_GROUP, GATEWAY} or role == "radiogroup":
        return "choice_group"
    if field_type == "checkbox" or role == "switch":
        return "multi_choice_group" if group_size(field) > 1 else "toggle"
    return "text_entry"


def group_size(field: dict[str, Any]) -> int:
    try:
        return max(1, int(field.get("group_size") or 1))
    except (TypeError, ValueError):
        return 1


def control_attributes(field: dict[str, Any]) -> dict[str, Any]:
    """The structural attributes that identify a control.

    Only what decides how the widget is operated: never the label, the name,
    the placeholder, or the ATS. A radio group on two companies' forms yields
    the same attributes and therefore the same control row.
    """
    tag, field_type, role = _lower(field, "tag"), _lower(field, "type"), _lower(field, "role")
    raw_aria = field.get("aria")
    aria: dict[str, Any] = raw_aria if isinstance(raw_aria, dict) else {}
    attributes: dict[str, Any] = {
        "tag": tag or None,
        "type": "button_group" if field_type == BUTTON_GROUP else field_type or None,
        "role": role or None,
        "multiple": True if field.get("multiple") is True else None,
        "options_in_dom": True
        if field.get("options") or field_type in {"radio", BUTTON_GROUP}
        else None,
        "group": ("many" if group_size(field) > 1 else "single")
        if field_type in {"radio", "checkbox"}
        else None,
        "aria_autocomplete": str(aria.get("autocomplete") or "").casefold() or None,
        "aria_haspopup": str(aria.get("haspopup") or "").casefold() or None,
    }
    return {key: value for key, value in attributes.items() if value is not None}


def control_key(field: dict[str, Any]) -> str:
    """One control's identity as a string: its kind and structural attributes."""
    return f"{classify(field)}|{json.dumps(control_attributes(field), sort_keys=True)}"


def preference_key(kind: str, attributes: dict[str, Any]) -> str:
    return f"{kind}|{json.dumps(attributes, sort_keys=True)}"


def question_of(field: dict[str, Any]) -> str:
    """The question a control answers: the group's question for a choice option."""
    if _lower(field, "type") in {"radio", "checkbox"} and str(field.get("group") or "").strip():
        return str(field["group"]).strip()
    if _lower(field, "type") == "radio":
        identity = field.get("name") or field.get("selector") or field.get("index")
        return f"Unidentified question ({identity})"
    return str(field.get("label") or field.get("name") or "").strip()


# ----- learned kinds ---------------------------------------------------------

# The read script the worker composes from a Kind's `reads`; a declaration
# never carries JavaScript. "selected" reads the texts of selected options or
# of pressed/selected/checked items the widget holds.
_READ_SCRIPTS = {
    "text": "(element) => String(element.innerText || element.textContent || '').trim()",
    "value": "(element) => String(element.value || '')",
    "selected": page_scripts.load("selected_texts"),
}
# A kind's read returns {value, label?, options?, required?, filled?}: the
# compose below wraps the reads expression the same way custom kinds do.


_READS = re.compile(r"text|value|selected|attribute:[a-z][a-z0-9_:-]{0,40}$")
# A selector must be plain CSS: no Playwright engine prefix, no chaining.
_ENGINE_PREFIX = re.compile(r"^\s*(?:[a-z_-]+=|internal:[a-z_-]+=)")


def _valid_selector(selector: str) -> bool:
    return bool(selector.strip()) and not (
        _ENGINE_PREFIX.match(selector) or ">>" in selector
    )


def _reads_script(reads: str) -> str:
    """The JS `read` one Kind's `reads` composes to, or "" for an unknown one."""
    if _READS.fullmatch(reads) is None:
        return ""
    if reads in _READ_SCRIPTS:
        return _READ_SCRIPTS[reads]
    if reads.startswith("attribute:"):
        # The name travels as an argument, never inside the script text.
        return "(element, name) => String(element.getAttribute(name) || '')"
    return ""


def _as_custom(kind: Any) -> Any:
    """A learned Kind shaped like a custom kind: same capture, same read."""
    from personal_os_worker.jobs.registry.kinds.custom import CustomKind

    script = _reads_script(kind.reads)
    read_arg = kind.reads[len("attribute:"):] if kind.reads.startswith("attribute:") else ""
    return CustomKind(
        name=kind.name,
        selector=kind.selector,
        read=f"(element, arg) => ({{value: ({script})(element, arg)}})",
        strategies={
            name: lambda _attempt: None for name in kind.strategies
        },
        read_arg=read_arg,
        declaration=kind,
    )


def learned_kinds(site: str) -> list[Any]:
    """The site's learned kinds, as custom-kind-shaped objects for capture."""
    from personal_os_worker.jobs import registry

    return [
        _as_custom(kind)
        for kind in registry.learned("kinds", site)
        if _reads_script(kind.reads) and _valid_selector(kind.selector)
    ]


def learned_kind(name: str, site: str) -> Any | None:
    """The one learned kind by name for a site, custom-shaped, or None."""
    return next(
        (kind for kind in learned_kinds(site) if kind.name == name), None
    )


def learned_question(control: Any, site: str) -> tuple[str, Any]:
    """The question a site's readers give this control's group, and the reader."""
    from personal_os_worker.jobs import registry

    for reader in registry.learned("questions", site):
        if not (
            _valid_selector(reader.group_selector)
            and _valid_selector(reader.question_selector)
        ):
            continue
        try:
            text = control.evaluate(
                page_scripts.load("group_question"),
                [reader.group_selector, reader.question_selector],
            )
        except Exception:
            continue
        if str(text or "").strip():
            return str(text).strip(), reader
    return "", None
