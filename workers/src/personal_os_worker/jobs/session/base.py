"""The shared attributes and the cross-mixin surface a session mixin sees.

Only annotations and TYPE_CHECKING stubs live here: __init__ on AutofillSession
sets the real attributes, and each stub's body is `...` — mypy checks every
self.method() a mixin makes against the sibling that defines it, while nothing
exists at runtime.
"""

from __future__ import annotations

from collections.abc import Callable
from typing import TYPE_CHECKING, Any

from playwright.sync_api import Page

from personal_os_worker.jobs.audit import Finding
from personal_os_worker.jobs.autofill_timing import AutofillTimings
from personal_os_worker.jobs.explain import Explainer
from personal_os_worker.jobs.fix.trial import Trial
from personal_os_worker.jobs.page_state import ApplicationPageState
from personal_os_worker.jobs.replay import Sighting
from personal_os_worker.jobs.session.context import SessionContext, SessionState
from personal_os_worker.jobs.short_answers import ShortQuestion, Verdict


class SessionBase:
    ctx: SessionContext
    state: SessionState
    page: Page
    timings: AutofillTimings
    trial: Trial
    evidence: dict[str, bytes]
    _explainer: Explainer | None
    _sent_calls: int

    if TYPE_CHECKING:
        def _save_now(self, *, quiet: bool = False) -> int: ...
        def answer_remote_facts(self, fields: list[dict[str, Any]]) -> None: ...
        def apply_value(
            self,
            fields: list[dict[str, Any]],
            field: dict[str, Any],
            value: str,
            *,
            source: str,
            resolver_id: str,
            fact_key: str | None = None,
            formatter: str | None = None,
            pattern_id: str | None = None,
        ) -> str | None: ...
        def ask_again(self, fields: list[dict[str, Any]], findings: list[Finding]) -> bool: ...
        def ask_for_fact(self, fields: list[dict[str, Any]], finding: Finding) -> bool: ...
        def audit_and_repair(
            self,
            fields: list[dict[str, Any]],
            result: dict[str, Any],
        ) -> None: ...
        def bind(self, question: str, fact_key: str, *, origin: str) -> str | None: ...
        def call_model[T](
            self,
            operation: Callable[..., T],
            *args: Any,
            **kwargs: Any,
        ) -> T | None: ...
        def capture_final_snapshot(self) -> None: ...
        def correct_answer(self, fields: list[dict[str, Any]], finding: Finding) -> bool: ...
        def emit_warnings(self, fields: list[dict[str, Any]]) -> None: ...
        def escalate(self, findings: list[Finding]) -> None: ...
        def expressions_by_fact(self) -> dict[str, list[str]]: ...
        def failure(self, question: str) -> dict[str, Any]: ...
        def fill_cover_letter(self, fields: list[dict[str, Any]]) -> None: ...
        def fill_deterministic(
            self,
            fields: list[dict[str, Any]],
            *,
            only: set[str] | None = None,
            note: str = 'appeared after answering',
        ) -> dict[str, Any]: ...
        def fill_long_form(self, fields: list[dict[str, Any]]) -> None: ...
        def fill_revealed(self, fields: list[dict[str, Any]], result: dict[str, Any]) -> None: ...
        def fill_with_claude(
            self,
            fields: list[dict[str, Any]],
            result: dict[str, Any],
        ) -> None: ...
        def final_url(self) -> str: ...
        def form_is_gone(self) -> bool: ...
        def gate_in_front(self) -> bool: ...
        def learn(
            self,
            verdicts: dict[str, Verdict],
            targets: dict[str, dict[str, Any]],
        ) -> set[str]: ...
        def may_ask(self, question: str) -> bool: ...
        def note_asked(self, question: str) -> None: ...
        def options_for(self, fields: list[dict[str, Any]], field: dict[str, Any]) -> list[str]: ...
        def persist_open(self, findings: list[Finding]) -> None: ...
        def persist_step(self, run_id: str, payload: dict[str, Any]) -> list[dict[str, Any]]: ...
        def problem_key(self, cause: str, question: str) -> str: ...
        def ranked_facts(self, questions: list[ShortQuestion]) -> dict[str, list[str]] | None: ...
        def refill_learned(
            self,
            fields: list[dict[str, Any]],
            learned: set[str],
            result: dict[str, Any],
        ) -> bool: ...
        def remember_issues(
            self,
            failures: list[dict[str, Any]],
            issues: list[dict[str, Any]],
            problem: Callable[[dict[str, Any]], tuple[str, str]],
        ) -> None: ...
        def repair_in_place(
            self,
            fields: list[dict[str, Any]],
            failures: list[dict[str, Any]],
            issues: list[dict[str, Any]],
        ) -> None: ...
        def report_open(self, findings: list[Finding]) -> None: ...
        def report_page_failure(
            self,
            category: str,
            message: str,
            *,
            artifact_paths: dict[str, str] | None = None,
            offered: list[str] | None = None,
        ) -> list[dict[str, Any]]: ...
        def report_review(self) -> None: ...
        def report_wall(self, category: str, message: str) -> Finding: ...
        def safe_point(self) -> None: ...
        def save_lesson(
            self,
            question: str,
            fact_key: str,
            expression: str | None,
            questions: list[str] | None,
            target: dict[str, Any],
            *,
            overriding: bool = False,
        ) -> str | None: ...
        def save_now(self) -> int: ...
        def sightings(self) -> list[Sighting] | None: ...
        def sleep(self) -> None: ...
        def upload_evidence(self, evidence: dict[str, bytes]) -> dict[str, str]: ...
        def wait_and_advance(self, fields: list[dict[str, Any]]) -> ApplicationPageState: ...
        def wait_for_form(self) -> list[dict[str, Any]] | None: ...
        def warn_once(self, key: str, message: str) -> None: ...
