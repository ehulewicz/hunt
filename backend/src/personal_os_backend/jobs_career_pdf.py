# Layout is Jake Gutierrez's "Jake's Resume" template as adapted for
# bin/Sam_Kim_resume_dec2027.pdf: 11pt newtx Times, small-caps section rules,
# and role-first two-row entries.
#
# Two deliberate departures from the supplied source:
#
#  1. \PassOptionsToPackage for color. newtx pulls color in itself on current
#     TeX Live, so a later \usepackage[usenames,dvipsnames]{color} raises an
#     option clash. Passing the options ahead of any loader keeps the intent.
#  2. \resumeEducation takes a prebuilt row block instead of a fixed pair of
#     degree rows. The supplied macro hard-codes exactly two degrees; building
#     the rows in Python emits identical output for two and still handles one.
PREAMBLE = r"""%-------------------------
% Resume in LaTeX
% Based off of: Jake Gutierrez's "Jake's Resume" template
% License: MIT
% Generated by the Personal OS API from the career record. Do not edit by hand.
%------------------------

\documentclass[letterpaper,11pt]{article}

% newtx loads color itself, so these options must reach the package before any
% other loader gets to it. Without this the document fails with an option clash.
\PassOptionsToPackage{usenames,dvipsnames}{color}

\usepackage[T1]{fontenc}
% Times text + math (real bold small caps; matches original metrics)
\usepackage{newtxtext,newtxmath}
\usepackage{latexsym}
\usepackage[empty]{fullpage}
\usepackage{titlesec}
\usepackage{marvosym}
\usepackage[usenames,dvipsnames]{color}
\usepackage{verbatim}
\usepackage{enumitem}
\usepackage[hidelinks]{hyperref}
\usepackage{fancyhdr}
\usepackage[english]{babel}
\usepackage{tabularx}
\input{glyphtounicode}

\pagestyle{fancy}
\fancyhf{} % clear all header and footer fields
\fancyfoot{}
\renewcommand{\headrulewidth}{0pt}
\renewcommand{\footrulewidth}{0pt}

% Adjust margins
\addtolength{\oddsidemargin}{-0.5in}
\addtolength{\evensidemargin}{-0.5in}
\addtolength{\textwidth}{1in}
\addtolength{\topmargin}{-.5in}
\addtolength{\textheight}{1.0in}

\urlstyle{same}

\raggedbottom
\raggedright
\setlength{\tabcolsep}{0in}

% Sections formatting
\titleformat{\section}{
  \vspace{-4pt}\scshape\raggedright\large
}{}{0em}{}[\color{black}\titlerule \vspace{-5pt}]

% Ensure that generate pdf is machine readable/ATS parsable
\pdfgentounicode=1

%-------------------------
% Custom commands
\newcommand{\resumeItem}[1]{
  \item\small{#1}\vspace{-2pt}
}

\newcommand{\resumeSubheading}[4]{
  \vspace{-2pt}\item
    \begin{tabular*}{0.97\textwidth}[t]{l@{\extracolsep{\fill}}r}
      \textbf{#1} & #2 \\
      \textit{\small#3} & \textit{\small #4} \\
    \end{tabular*}\vspace{-6pt}
}

% School with any number of degree lines plus a coursework line, all on one
% baseline grid. #3 carries the already-formatted rows.
\newcommand{\resumeEducation}[3]{
  \vspace{-2pt}\item
    \begin{tabular*}{0.97\textwidth}[t]{l@{\extracolsep{\fill}}r}
      \textbf{#1} & #2 \\
      #3
    \end{tabular*}\vspace{-7pt}
}

\newcommand{\resumeSubSubheading}[2]{
    \item
    \begin{tabular*}{0.97\textwidth}{l@{\extracolsep{\fill}}r}
      \textit{\small#1} & \textit{\small #2} \\
    \end{tabular*}\vspace{-7pt}
}

\newcommand{\resumeProjectHeading}[2]{
    \item
    \begin{tabular*}{0.97\textwidth}{l@{\extracolsep{\fill}}r}
      \small#1 & #2 \\
    \end{tabular*}\vspace{-7pt}
}

\newcommand{\resumeSubItem}[1]{\resumeItem{#1}\vspace{-4pt}}

\renewcommand\labelitemii{$\vcenter{\hbox{\tiny$\bullet$}}$}

\newcommand{\resumeSubHeadingListStart}{\begin{itemize}[leftmargin=0.15in, label={}]}
\newcommand{\resumeSubHeadingListEnd}{\end{itemize}}
\newcommand{\resumeItemListStart}{\begin{itemize}}
\newcommand{\resumeItemListEnd}{\end{itemize}\vspace{-5pt}}
"""

REPRODUCIBLE_EPOCH = "946684800"  # 2000-01-01T00:00:00Z

# The preamble is the single declaration of what TeX must provide, so the
# pre-flight check reads its loaders rather than keeping a second list.
USEPACKAGE = re.compile(r"\\usepackage(?:\[[^\]]*\])?\{([^}]*)\}")
INPUT_FILE = re.compile(r"\\input\{([^}]*)\}")

# A resume build is valid only when the reference-style layout stays on one page.
MAXIMUM_PAGES: int | None = 1

# Rendered in this order. A section with no entries emits nothing at all.
ENTRY_SECTIONS: tuple[tuple[str, str], ...] = (
    ("experience", "Experience"),
    ("research", "Research"),
    ("projects", "Projects"),
    ("activities", "Activities"),
)

# Keys that say whether a record item prints; the projection drops them.
SCHOOL_META = ("level", "primary", "onResume")
ENTRY_META = ("id", "onResume", "moreBullets")


class PdfError(RuntimeError):
    """A document the build refused: the compile, the page count, or a bullet."""


def printed_document(document: dict[str, Any]) -> dict[str, Any]:
    """The on-resume projection of a career document: exactly what prints.

    Off-resume schools and entries drop out; a printed entry keeps only its
    `bullets`. Ids, `onResume`, `moreBullets`, `primary`, and `level` never
    reach the LaTeX, so editing them cannot change the PDF bytes.
    """
    printed: dict[str, Any] = {
        "contact": dict(document.get("contact") or {}),
        "education": [
            {key: value for key, value in school.items() if key not in SCHOOL_META}
            for school in document.get("education") or []
            if school.get("onResume", True)
        ],
    }
    for key, _ in ENTRY_SECTIONS:
        printed[key] = [
            {name: value for name, value in entry.items() if name not in ENTRY_META}
            for entry in document.get(key) or []
            if entry.get("onResume", True)
        ]
    printed["skills"] = list(document.get("skills") or [])
    return printed


def preamble_requirements() -> tuple[str, ...]:
    """Every TeX file the preamble loads, named the way `kpsewhich` resolves it."""
    names = [
        f"{name.strip()}.sty"
        for group in USEPACKAGE.findall(PREAMBLE)
        for name in group.split(",")
        if name.strip()
    ]
    names.extend(f"{name.strip()}.tex" for name in INPUT_FILE.findall(PREAMBLE) if name.strip())
    return tuple(dict.fromkeys(names))


def latex_errors(log: Path) -> list[str]:
    """The `! ...` lines latexmk wrote, which name what actually failed."""
    try:
        text = log.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return []
    return [line.strip() for line in text.splitlines() if line.startswith("! ")]


def latex_environment() -> dict[str, str]:
    environment = os.environ.copy()
    environment["SOURCE_DATE_EPOCH"] = REPRODUCIBLE_EPOCH
    environment["FORCE_SOURCE_DATE"] = "1"
    return environment


# AGENTS.md: a resume bullet never runs past two rendered lines.
MAXIMUM_BULLET_LINES = 2
BULLET_MARK = "•"


def build_resume_pdf(printed: dict[str, Any]) -> bytes:
    """Compile the printed projection to the resume PDF's bytes."""
    with tempfile.TemporaryDirectory() as directory:
        pdf = compile_pdf(build_latex(printed), Path(directory), "resume", pages=MAXIMUM_PAGES)
        layout = subprocess.run(
            ["pdftotext", "-layout", str(pdf), "-"],
            check=False,
            capture_output=True,
            text=True,
            timeout=15,
        )
        if layout.returncode != 0:
            raise PdfError("Could not read the generated resume to check bullet lengths")
        long = overlong_bullets(layout.stdout)
        if long:
            raise PdfError(
                f"A bullet runs past {MAXIMUM_BULLET_LINES} lines; split or cut: "
                + "; ".join(f"{text!r} ({lines} lines)" for text, lines in long)
            )
        return pdf.read_bytes()


def overlong_bullets(layout: str) -> list[tuple[str, int]]:
    """Bullets longer than the limit, read from `pdftotext -layout` output.

    A bullet's first line starts with the bullet mark; its continuation lines
    are indented past the mark. A blank line, a less-indented line, or another
    mark ends it.
    """
    found: list[tuple[str, int]] = []
    current: tuple[str, int, int] | None = None  # (opening words, mark column, lines)

    def close() -> None:
        if current is not None and current[2] > MAXIMUM_BULLET_LINES:
            found.append((current[0], current[2]))

    for line in layout.splitlines():
        stripped = line.strip()
        column = len(line) - len(line.lstrip())
        if stripped.startswith(BULLET_MARK):
            close()
            words = " ".join(stripped.removeprefix(BULLET_MARK).split()[:6])
            current = (words, column, 1)
        elif current is not None and stripped and column > current[1]:
            current = (current[0], current[1], current[2] + 1)
        else:
            close()
            current = None
    close()
    return found


def compile_pdf(latex: str, output_directory: Path, stem: str, *, pages: int | None) -> Path:
    """Run latexmk on `latex` as `<stem>.tex` and verify the page budget."""
    output_directory.mkdir(parents=True, exist_ok=True)
    source = output_directory / f"{stem}.tex"
    source.write_text(latex, encoding="utf-8")
    process = subprocess.run(
        [
            "latexmk",
            "-pdf",
            "-interaction=nonstopmode",
            "-halt-on-error",
            f"-outdir={output_directory}",
            str(source),
        ],
        check=False,
        capture_output=True,
        env=latex_environment(),
        text=True,
        timeout=120,
    )
    pdf = output_directory / f"{stem}.pdf"
    if process.returncode != 0 or not pdf.exists():
        reported = latex_errors(output_directory / f"{stem}.log")
        if not reported:
            console = [
                line.strip()
                for line in (process.stdout + "\n" + process.stderr).splitlines()
                if line.strip()
            ]
            reported = console[-1:] or ["latexmk reported no error"]
        raise PdfError(f"latexmk failed for {stem}: {' '.join(reported[:3])[:500]}")
    page_check = subprocess.run(
        ["pdfinfo", str(pdf)], check=False, capture_output=True, text=True, timeout=15
    )
    found = re.search(r"^Pages:\s+(\d+)$", page_check.stdout, re.MULTILINE)
    if page_check.returncode != 0 or found is None:
        raise PdfError(f"Could not verify the generated {stem} page count")
    if pages is not None and int(found.group(1)) > pages:
        raise PdfError(
            f"{stem} must stay within {pages} page(s); generated {found.group(1)}"
        )
    return pdf


def build_latex(resume: dict[str, Any]) -> str:
    serialized = json.dumps(resume, sort_keys=True, separators=(",", ":"))
    trailer_id = hashlib.sha256(serialized.encode()).hexdigest()[:32].upper()
    parts = [
        PREAMBLE,
        rf"\pdftrailerid{{<{trailer_id}><{trailer_id}>}}",
        r"\begin{document}",
    ]
    parts.extend(build_header(resume.get("contact", {})))
    parts.extend(build_education(resume.get("education", [])))
    for key, label in ENTRY_SECTIONS:
        parts.extend(build_entries(label, resume.get(key, [])))
    parts.extend(build_skills(resume.get("skills", [])))
    parts.append(r"\end{document}")
    return "\n".join(parts) + "\n"


def build_header(contact: dict[str, Any]) -> list[str]:
    details: list[str] = []
    citizenship = str(contact.get("citizenship", "")).strip()
    if citizenship:
        details.append(escape(citizenship))
    phone = str(contact.get("phone", "")).strip()
    if phone:
        details.append(escape(phone))
    email = str(contact.get("email", "")).strip()
    if email:
        details.append(rf"\href{{mailto:{email}}}{{\underline{{{escape(email)}}}}}")
    for key in ("linkedin", "github"):
        link = str(contact.get(key, "")).strip()
        if link:
            details.append(rf"\href{{{link}}}{{\underline{{{escape(display_url(link))}}}}}")
    return [
        r"\begin{center}",
        rf"    \textbf{{\Huge \scshape {escape(str(contact.get('name', '')))}}} \\ \vspace{{1pt}}",
        r"    \small " + " $|$\n    ".join(details),
        r"\end{center}",
    ]


def build_education(schools: list[dict[str, Any]]) -> list[str]:
    """One \\resumeEducation item per printed school, in document order."""
    if not schools:
        return []
    lines = [r"\section{Education}", r"  \resumeSubHeadingListStart"]
    for school in schools:
        rows = [
            rf"      \textit{{\small {escape(degree)}}} & \textit{{\small {escape(date)}}} \\"
            for degree, date in education_degrees(school)
        ]
        courses = ", ".join(
            str(course).strip() for course in school.get("courses", []) if str(course).strip()
        )
        if courses:
            rows.append(rf"      \small {escape(courses)} & \\")
        lines.extend(
            [
                r"    \resumeEducation",
                (
                    rf"      {{{escape(str(school.get('school', '')))}}}"
                    rf"{{{escape(str(school.get('location', '')))}}}"
                ),
                "      {%",
                *rows,
                "      }",
            ]
        )
    lines.append(r"  \resumeSubHeadingListEnd")
    return lines


def education_degrees(education: dict[str, Any]) -> list[tuple[str, str]]:
    """Return the degree rows as (text, date) pairs.

    ``degrees`` is the current shape and carries one entry per awarded degree.
    The older flat ``degree``/``threads``/``gpa``/``graduation`` fields still
    render, as a single row.
    """
    declared = education.get("degrees")
    if isinstance(declared, list) and declared:
        return [
            (str(row.get("degree", "")).strip(), str(row.get("date", "")).strip())
            for row in declared
            if isinstance(row, dict)
        ]
    degree = str(education.get("degree", "")).strip()
    if not degree:
        return []
    threads = str(education.get("threads", "")).strip()
    if threads:
        degree = f"{degree}, Specializations in {threads}"
    gpa = str(education.get("gpa", "")).strip()
    scale = str(education.get("gpaScale", "")).strip()
    if gpa and scale:
        gpa = f"{gpa}/{scale}"
    if gpa:
        degree = f"{degree} — GPA: {gpa}"
    return [(degree, str(education.get("graduation", "")).strip())]


def build_entries(title: str, entries: list[dict[str, Any]]) -> list[str]:
    """Render one section, or nothing when the section is empty.

    An entry with an organization gets the two-row role-first heading. One
    without gets the single-row project heading, which is how the reference sets
    projects and anything else that has no separate employer.
    """
    if not entries:
        return []
    lines = [rf"\section{{{title}}}", r"  \resumeSubHeadingListStart"]
    for entry in entries:
        role = escape(str(entry.get("title", "")))
        org = escape(str(entry.get("org", "") or ""))
        location = escape(str(entry.get("location", "") or ""))
        date = escape(str(entry.get("date", "")))
        qualifier = escape(str(entry.get("qualifier", "") or "").strip())
        if qualifier:
            date = rf"\textit{{{qualifier}}} $|$ {date}"
        if org:
            lines.append(rf"    \resumeSubheading{{{role}}}{{{date}}}{{{org}}}{{{location}}}")
        else:
            lines.append(rf"    \resumeProjectHeading{{\textbf{{{role}}}}}{{{date}}}")
        lines.append(r"      \resumeItemListStart")
        lines.extend(
            rf"        \resumeItem{{{escape(str(bullet))}}}" for bullet in entry.get("bullets", [])
        )
        lines.append(r"      \resumeItemListEnd")
    lines.append(r"  \resumeSubHeadingListEnd")
    return lines


def build_skills(skills: list[dict[str, Any]]) -> list[str]:
    """Render every skill category as one item of backslash-separated lines."""
    if not skills:
        return []
    rows = [
        rf"     \textbf{{{escape(str(skill.get('category', '')))}}}"
        rf"{{: {escape(str(skill.get('items', '')))}}}"
        for skill in skills
    ]
    return [
        r"\section{Technical Skills}",
        r" \begin{itemize}[leftmargin=0.15in, label={}]",
        r"    \small{\item{",
        " \\\\\n".join(rows),
        r"    }}",
        r" \end{itemize}",
    ]


def display_url(url: str) -> str:
    return re.sub(r"^https?://(www\.)?", "", url).rstrip("/")


def escape(value: str) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
        "|": r"\textbar{}",
        "–": "--",  # noqa: RUF001 - the authored en dash intentionally maps to TeX.
        "—": "---",
    }
    return "".join(replacements.get(character, character) for character in value)


def build_letter_latex(
    contact: dict[str, Any], text: str, *, date: str, company: str
) -> str:
    trailer_id = hashlib.sha256(text.encode()).hexdigest()[:32].upper()
    parts = [PREAMBLE, rf"\pdftrailerid{{<{trailer_id}><{trailer_id}>}}", r"\begin{document}"]
    parts.extend(build_header(contact))
    parts.append(r"\vspace{10pt}")
    parts.append(rf"\noindent {escape(date)}\par\vspace{{4pt}}")
    parts.append(rf"\noindent {escape(company)}\par\vspace{{10pt}}")
    for paragraph in re.split(r"\n\s*\n", text.strip()):
        lines = [escape(line.strip()) for line in paragraph.splitlines() if line.strip()]
        parts.append(r"\noindent " + r" \\ ".join(lines) + r"\par\vspace{8pt}")
    parts.append(r"\end{document}")
    return "\n".join(parts) + "\n"


def build_letter_pdf(
    contact: dict[str, Any], text: str, *, date: str, company: str
) -> bytes:
    """Compile a cover letter to one page of PDF bytes."""
    with tempfile.TemporaryDirectory() as directory:
        latex = build_letter_latex(contact, text, date=date, company=company)
        pdf = compile_pdf(latex, Path(directory), "cover_letter", pages=1)
        return pdf.read_bytes()


class ResumeCompiler(Protocol):
    """What the routes ask of the build: the projection, and the two PDFs."""

    def printed_document(self, document: dict[str, Any]) -> dict[str, Any]: ...

    def build_resume_pdf(self, printed: dict[str, Any]) -> bytes: ...

    def build_letter_pdf(
        self, contact: dict[str, Any], text: str, *, date: str, company: str
    ) -> bytes: ...


class LatexCompiler:
    """The module's functions behind the compiler protocol, for injection."""

    def printed_document(self, document: dict[str, Any]) -> dict[str, Any]:
        return printed_document(document)

    def build_resume_pdf(self, printed: dict[str, Any]) -> bytes:
        return build_resume_pdf(printed)

    def build_letter_pdf(
        self, contact: dict[str, Any], text: str, *, date: str, company: str
    ) -> bytes:
        return build_letter_pdf(contact, text, date=date, company=company)


async def get_pdf_compiler(request: Request) -> ResumeCompiler:
    return LatexCompiler()


router = APIRouter(prefix="/v1/jobs", tags=["documents"])
Compiler = Annotated[ResumeCompiler, Depends(get_pdf_compiler)]


class CoverLetterPdf(BaseModel):
    model_config = ConfigDict(extra="forbid")

    text: str = Field(min_length=1, max_length=20000)
    company: str = Field(max_length=300)
    date: str = Field(max_length=100)


async def _contact(request: Request, user_id: UUID) -> dict[str, str]:
    """The resume header, from the user's contact facts."""
    # Deferred: jobs_career imports this module for the compiler.
    from personal_os_backend.jobs_career import contact_facts

    settings: Settings = request.app.state.settings
    pool: AsyncConnectionPool[Any] = request.app.state.pool
    async with (
        pool.connection(timeout=settings.database_pool_timeout_seconds) as connection,
        connection.transaction(),
    ):
        await connection.execute("set local role personal_os_api")
        return await contact_facts(connection, user_id)


@router.post("/cover-letter/pdf")
async def cover_letter_pdf(
    item: CoverLetterPdf,
    principal: CurrentPrincipal,
    compiler: Compiler,
    request: Request,
) -> Response:
    """A one-page letter with the resume's header; nothing is stored."""
    contact = await _contact(request, principal.user_id)
    try:
        pdf = await asyncio.to_thread(
            compiler.build_letter_pdf,
            contact,
            item.text,
            date=item.date,
            company=item.company,
        )
    except PdfError as error:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, str(error)) from None
    return Response(content=pdf, media_type="application/pdf")
